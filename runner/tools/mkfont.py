#!/usr/bin/env python3
"""Generates runner/font_data.h: three bitmap fonts (small/medium/large) for
casioplot.draw_string. "small" is Pillow's built-in bitmap font; medium and
large are rendered from DejaVu Sans Bold. Needs Pillow; the output is
committed, so building the runner doesn't need this script.

    python3 tools/mkfont.py /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf > font_data.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont


def render(font, height, threshold=128):
    glyphs = []
    for code in range(32, 127):
        ch = chr(code)
        adv = max(1, round(font.getlength(ch)))
        img = Image.new("L", (adv + 8, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        rows = []
        for y in range(height):
            bits = 0
            for x in range(min(adv, 32)):
                if img.getpixel((x, y)) > threshold:
                    bits |= 1 << (31 - x)
            rows.append(bits)
        glyphs.append((adv, rows))
    return glyphs


def main():
    bold = sys.argv[1]
    small = ImageFont.load_default_imagefont() if hasattr(ImageFont, "load_default_imagefont") \
        else ImageFont.load_default()
    medium = ImageFont.truetype(bold, 13)
    large = ImageFont.truetype(bold, 17)
    fonts = {
        "small": render(small, 11),
        "medium": render(medium, sum(medium.getmetrics())),
        "large": render(large, sum(large.getmetrics())),
    }
    print("// Generated by tools/mkfont.py. small: Pillow's bitmap font; medium/large:")
    print("// DejaVu Sans Bold (Bitstream Vera licence). Do not edit by hand.")
    print("#include <stdint.h>")
    for name, glyphs in fonts.items():
        data, offs, widths = [], [], []
        for w, rows in glyphs:
            offs.append(len(data))
            widths.append(w)
            data.extend(rows)
        print(f"static const uint32_t font_{name}_rows[] = {{")
        for i in range(0, len(data), 8):
            print("    " + ", ".join(f"0x{v:08X}" for v in data[i:i + 8]) + ",")
        print("};")
        print(f"static const uint16_t font_{name}_offs[95] = {{ {', '.join(map(str, offs))} }};")
        print(f"static const uint8_t font_{name}_widths[95] = {{ {', '.join(map(str, widths))} }};")
        print(f"#define FONT_{name.upper()}_HEIGHT {len(glyphs[0][1])}")


main()
